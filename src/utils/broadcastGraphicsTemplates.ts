export function summarizeAdPosition(elements: GraphicsElement[], cw = 1920, ch = 1080): string {
  if (!elements || elements.length === 0) return 'Empty';
  let minX = cw;
  let minY = ch;
  let maxX = 0;
  let maxY = 0;
  for (const el of elements) {
    if (!el.visible) continue;
    minX = Math.min(minX, el.x);
    minY = Math.min(minY, el.y);
    maxX = Math.max(maxX, el.x + el.width);
    maxY = Math.max(maxY, el.y + el.height);
  }
  const cx = (minX + maxX) / 2;
  const cy = (minY + maxY) / 2;
  const v = cy < ch * 0.35 ? 'Top' : cy > ch * 0.65 ? 'Bottom' : 'Center';
  const h = cx < cw * 0.35 ? 'Left' : cx > cw * 0.65 ? 'Right' : 'Center';
  if (v === 'Center' && h === 'Center') return 'Center Stage';
  if (maxX - minX > cw * 0.65) return `${v} Full Bar`;
  return `${v} ${h}`;
}
