export function makeElementId(prefix = 'el'): string {
  return `${prefix}_${Math.random().toString(36).slice(2, 9)}_${Date.now().toString(36).slice(-4)}`;
}

export function defaultAnimation(style: GraphicsAnimationStyle = 'slide-bottom'): GraphicsElementAnimation {
  const isContinuous = style === 'pulse' || style === 'bounce' || style === 'marquee';
  return {
    style: isContinuous ? 'fade-in' : style,
    exitStyle: 'fade-out',
    continuousStyle: isContinuous ? style : 'none',
    durationMs: 420,
    exitDurationMs: 340,
    delayMs: 0,
    speed: 'normal',
    direction: 'normal',
    easing: 'cubic-bezier(0.16, 1, 0.3, 1)',
    repeatCount: 0,
    intensity: 'medium',
    loop: isContinuous,
    startTrigger: isContinuous ? 'continuous' : 'on_enter',
    endBehavior: isContinuous ? 'loop' : 'hold',
    startTimeMs: 0,
    endTimeMs: null,
  };
}

export function createDefaultElement(
  type: GraphicsElementType,
  opts?: {
    canvasWidth?: number;
    canvasHeight?: number;
    zIndex?: number;
    shapeKind?: GraphicsShapeKind;
    src?: string;
    iconName?: string;
    layerName?: string;
    matchId?: string;
    tournamentId?: string;
  }
): GraphicsElement {
  const cw = opts?.canvasWidth || 1920;
  const ch = opts?.canvasHeight || 1080;
  const zIndex = opts?.zIndex ?? 10;

  if (type === 'text') {
    return {
      id: makeElementId('txt'),
      type: 'text',
      layerName: opts?.layerName || 'Promotional Text',
      x: Math.round(cw * 0.18),
      y: Math.round(ch * 0.78),
      width: 680,
      height: 76,
      rotation: 0,
      scaleX: 1,
      scaleY: 1,
      anchorPoint: 'center',
      lockAspectRatio: false,
      opacity: 1,
      zIndex,
      visible: true,
      locked: false,
      text: 'POWERED BY MAIDANLIVE SPORTS',
      fontFamily: '"Outfit", sans-serif',
      fontSize: 34,
      fontWeight: '800',
      fontColor: '#ffffff',
      backgroundColor: '#0f172ae6',
      backgroundOpacity: 1,
      textAlign: 'center',
      verticalAlign: 'middle',
      letterSpacing: 1.5,
      lineHeight: 1.2,
      wordWrap: true,
      textTransform: 'none',
      textDirection: 'ltr',
      borderWidth: 2,
      borderColor: '#ea580c',
      borderStyle: 'solid',
      borderRadius: 12,
      paddingX: 20,
      paddingY: 12,
      shadowEnabled: true,
      shadowColor: 'rgba(0,0,0,0.55)',
      shadowBlur: 18,
      shadowOffsetX: 0,
      shadowOffsetY: 6,
      animation: defaultAnimation('slide-bottom'),
    };
  }

  if (type === 'image') {
    return {
      id: makeElementId('img'),
      type: 'image',
      layerName: opts?.layerName || 'Sponsor Banner Image',
      x: Math.round(cw * 0.25),
      y: Math.round(ch * 0.74),
      width: 640,
      height: 160,
      rotation: 0,
      scaleX: 1,
      scaleY: 1,
      anchorPoint: 'center',
      lockAspectRatio: true,
      opacity: 1,
      zIndex,
      visible: true,
      locked: false,
      src: opts?.src || '',
      objectFit: 'contain',
      crop: { top: 0, right: 0, bottom: 0, left: 0 },
      flipX: false,
      flipY: false,
      imageMask: 'none',
      imageAlign: 'center',
      backgroundColor: 'transparent',
      backgroundOpacity: 1,
      borderWidth: 0,
      borderColor: '#ffffff',
      borderStyle: 'solid',
      borderRadius: 12,
      shadowEnabled: true,
      shadowColor: 'rgba(0,0,0,0.45)',
      shadowBlur: 16,
      shadowOffsetX: 0,
      shadowOffsetY: 6,
      animation: defaultAnimation('fade-in'),
    };
  }

  if (type === 'logo') {
    return {
      id: makeElementId('logo'),
      type: 'logo',
      layerName: opts?.layerName || 'Sponsor Logo',
      x: cw - 250,
      y: 48,
      width: 180,
      height: 120,
      rotation: 0,
      scaleX: 1,
      scaleY: 1,
      anchorPoint: 'center',
      lockAspectRatio: true,
      opacity: 1,
      zIndex,
      visible: true,
      locked: false,
      src: opts?.src || '',
      objectFit: 'contain',
      flipX: false,
      flipY: false,
      imageMask: 'none',
      imageAlign: 'center',
      logoPreset: 'top-right',
      backgroundColor: 'rgba(15, 23, 42, 0.85)',
      backgroundOpacity: 1,
      borderWidth: 1,
      borderColor: 'rgba(255,255,255,0.2)',
      borderStyle: 'solid',
      borderRadius: 14,
      paddingX: 12,
      paddingY: 12,
      shadowEnabled: true,
      shadowColor: 'rgba(0,0,0,0.5)',
      shadowBlur: 20,
      shadowOffsetX: 0,
      shadowOffsetY: 6,
      animation: defaultAnimation('zoom-in'),
    };
  }

  if (type === 'qr') {
    const publicOrigin = getPublicWebOrigin();
    const matchLink = opts?.matchId
      ? `${publicOrigin}/live/${opts.matchId}`
      : publicOrigin;
    return {
      id: makeElementId('qr'),
      type: 'qr',
      layerName: opts?.layerName || 'Sponsor QR Code',
      x: cw - 260,
      y: ch - 300,
      width: 196,
      height: 236,
      rotation: 0,
      scaleX: 1,
      scaleY: 1,
      anchorPoint: 'center',
      lockAspectRatio: false,
      opacity: 1,
      zIndex,
      visible: true,
      locked: false,
      qrLinkType: opts?.matchId ? 'match' : 'sponsor',
      qrUrl: matchLink,
      qrFgColor: '#0f172a',
      qrBgColor: '#ffffff',
      qrCenterLogoUrl: '',
      qrCenterLogoSizePct: 22,
      qrCaption: 'SCAN TO VISIT',
      qrCaptionColor: '#ffffff',
      backgroundColor: 'rgba(15, 23, 42, 0.92)',
      backgroundOpacity: 1,
      borderWidth: 2,
      borderColor: '#ea580c',
      borderStyle: 'solid',
      borderRadius: 14,
      paddingX: 12,
      paddingY: 12,
      shadowEnabled: true,
      shadowColor: 'rgba(0,0,0,0.55)',
      shadowBlur: 20,
      shadowOffsetX: 0,
      shadowOffsetY: 8,
      animation: defaultAnimation('pop-in'),
    };
  }

  if (type === 'icon') {
    return {
      id: makeElementId('ico'),
      type: 'icon',
      layerName: opts?.layerName || 'Broadcast Icon',
      x: Math.round(cw * 0.5) - 48,
      y: Math.round(ch * 0.5) - 48,
      width: 96,
      height: 96,
      rotation: 0,
      scaleX: 1,
      scaleY: 1,
      anchorPoint: 'center',
      lockAspectRatio: true,
      opacity: 1,
      zIndex,
      visible: true,
      locked: false,
      iconName: opts?.iconName || 'trophy',
      iconColor: '#ffffff',
      iconStrokeWidth: 2,
      backgroundColor: '#ea580c',
      backgroundOpacity: 1,
      borderWidth: 0,
      borderColor: '#ffffff',
      borderStyle: 'solid',
      borderRadius: 18,
      paddingX: 18,
      paddingY: 18,
      shadowEnabled: true,
      shadowColor: 'rgba(0,0,0,0.45)',
      shadowBlur: 18,
      shadowOffsetX: 0,
      shadowOffsetY: 6,
      animation: defaultAnimation('pop-in'),
    };
  }

  const shapeKind = opts?.shapeKind || 'rounded_rect';
  const isLine = shapeKind === 'line' || shapeKind === 'divider';
  const isCircleOrEllipse = shapeKind === 'circle' || shapeKind === 'ellipse';
  const isContainer = shapeKind === 'container';
  return {
    id: makeElementId('shp'),
    type: 'shape',
    layerName:
      opts?.layerName ||
      (shapeKind === 'circle'
        ? 'Circle Badge'
        : shapeKind === 'ellipse'
          ? 'Ellipse Shape'
          : isContainer
            ? 'Glass Container'
            : isLine
              ? 'Accent Divider'
              : 'Background Card'),
    x: isLine ? 120 : 80,
    y: isLine ? ch - 130 : ch - 210,
    width: isLine ? 720 : shapeKind === 'circle' ? 180 : 840,
    height: isLine ? 6 : shapeKind === 'circle' ? 180 : 140,
    rotation: 0,
    scaleX: 1,
    scaleY: 1,
    anchorPoint: 'center',
    lockAspectRatio: shapeKind === 'circle',
    opacity: isContainer ? 0.88 : 0.96,
    zIndex,
    visible: true,
    locked: false,
    shapeKind,
    backgroundColor: isLine ? '#ea580c' : isContainer ? 'rgba(15, 23, 42, 0.78)' : '#0f172a',
    backgroundOpacity: 1,
    gradient: {
      enabled: !isLine && !isCircleOrEllipse && !isContainer,
      from: '#0f172a',
      to: '#1e293b',
      angle: 135,
    },
    borderWidth: isLine ? 0 : 2,
    borderColor: isContainer ? 'rgba(255,255,255,0.28)' : '#ea580c',
    borderStyle: 'solid',
    borderRadius:
      shapeKind === 'circle' || shapeKind === 'ellipse'
        ? 9999
        : shapeKind === 'rectangle'
          ? 0
          : 16,
    shadowEnabled: !isLine,
    shadowColor: 'rgba(0,0,0,0.55)',
    shadowBlur: 24,
    shadowOffsetX: 0,
    shadowOffsetY: 8,
    animation: defaultAnimation('slide-left'),
  };
}

