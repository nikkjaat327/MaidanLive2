import React, { useEffect, useState } from 'react';
import { Navigate, useNavigate } from 'react-router-dom';
import { KeyRound, ShieldCheck } from 'lucide-react';
import { useAuth } from '../../hooks/useAuth.ts';
import { authService } from '../../services/auth/authService.ts';
import { extractApiError } from '../../services/api/httpClient.ts';
import { FeedbackBanner } from '../../components/common/FeedbackBanner.tsx';

export function AdminLoginPage() {
  const { adminUser, adminLoading, loginAdmin, bootstrapSuperAdmin } = useAuth();
  const navigate = useNavigate();

  const [checkingSetup, setCheckingSetup] = useState(true);
  const [needsSetup, setNeedsSetup] = useState(false);
  const [requiresSetupKey, setRequiresSetupKey] = useState(false);

  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [setupKey, setSetupKey] = useState('');
  const [requires2FA, setRequires2FA] = useState(false);
  const [totpCode, setTotpCode] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [infoMsg, setInfoMsg] = useState<string | null>(null);

  useEffect(() => {
    authService
      .getAdminSetupStatus()
      .then((res) => {
        setNeedsSetup(res.needsSetup);
        setRequiresSetupKey(res.requiresSetupKey);
      })
      .catch(() => {
        setNeedsSetup(false);
      })
      .finally(() => setCheckingSetup(false));
  }, []);

  if (!adminLoading && adminUser) {
    const dest = adminUser.role === 'BROADCASTER' ? '/broadcaster' : '/admin/dashboard';
    return <Navigate to={dest} replace />;
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    try {
      setSubmitting(true);
      setError(null);
      setInfoMsg(null);
      if (needsSetup) {
        await bootstrapSuperAdmin({
          name,
          email,
          password,
          setupKey: requiresSetupKey ? setupKey : undefined,
        });
        navigate('/admin/dashboard', { replace: true });
      } else {
        const res = await loginAdmin(
          email,
          password,
          requires2FA ? totpCode.trim() : undefined
        );
        if (res.requires2FA) {
          setRequires2FA(true);
          setInfoMsg(res.message || 'Enter the 6-digit code from your authenticator app.');
          return;
        }
        const dest = res.user?.role === 'BROADCASTER' ? '/broadcaster' : '/admin/dashboard';
        navigate(dest, { replace: true });
      }
    } catch (err: any) {
      if (err?.response?.data?.requires2FA) {
        setRequires2FA(true);
      }
      setError(extractApiError(err, 'Authentication failed.'));
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <div className="min-h-screen bg-slate-950 flex items-center justify-center px-4 py-12">
      <div className="w-full max-w-md bg-slate-900 border border-slate-800 text-slate-100 rounded-2xl p-6 sm:p-8 space-y-6 shadow-2xl">
        <div className="space-y-2">
          <div className="w-10 h-10 rounded-xl bg-[#EA580C] text-white flex items-center justify-center">
            {requires2FA ? <KeyRound className="w-5 h-5" /> : <ShieldCheck className="w-5 h-5" />}
          </div>
          <h1 className="font-display text-2xl font-bold text-white">
            {checkingSetup
              ? 'MaidanLive Admin Portal'
              : needsSetup
                ? 'Initialize Super Admin'
                : requires2FA
                  ? 'Two-Factor Verification'
                  : 'Admin Portal Sign In'}
          </h1>
          <p className="text-sm text-slate-400">
            {needsSetup
              ? 'No Super Admin exists in the database yet. Create the primary Super Admin account to lock setup and unlock broadcast controls.'
              : requires2FA
                ? 'Enter the 6-digit TOTP code generated by your authenticator app to complete sign-in.'
                : 'Restricted to authorized administrators, tournament organizers, broadcasters, and scorers.'}
          </p>
        </div>

        <FeedbackBanner type="error" message={error} onDismiss={() => setError(null)} />
        <FeedbackBanner type="info" message={infoMsg} onDismiss={() => setInfoMsg(null)} />

        {checkingSetup ? (
          <div className="py-8 text-center text-sm text-slate-400">
            Checking initialization status...
          </div>
        ) : (
          <form onSubmit={handleSubmit} className="space-y-4">
            {needsSetup && (
              <div>
                <label className="block text-sm font-medium text-slate-300 mb-1">
                  Super Admin Name
                </label>
                <input
                  type="text"
                  required
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder="Full name"
                  className="w-full min-h-[44px] px-3.5 py-2 text-sm bg-slate-950 text-white border border-slate-700 rounded-lg focus:outline-none focus:ring-2 focus:ring-[#EA580C]"
                />
              </div>
            )}

            <div>
              <label className="block text-sm font-medium text-slate-300 mb-1">Email</label>
              <input
                type="email"
                required
                autoComplete="email"
                value={email}
                onChange={(e) => setEmail(e.target.value)}
                disabled={requires2FA}
                className="w-full min-h-[44px] px-3.5 py-2 text-sm bg-slate-950 text-white border border-slate-700 rounded-lg focus:outline-none focus:ring-2 focus:ring-[#EA580C] disabled:opacity-60"
              />
            </div>

            {!requires2FA && (
              <div>
                <label className="block text-sm font-medium text-slate-300 mb-1">Password</label>
                <input
                  type="password"
                  required
                  minLength={needsSetup ? 8 : 1}
                  autoComplete={needsSetup ? 'new-password' : 'current-password'}
                  value={password}
                  onChange={(e) => setPassword(e.target.value)}
                  placeholder={needsSetup ? 'Minimum 8 characters' : ''}
                  className="w-full min-h-[44px] px-3.5 py-2 text-sm bg-slate-950 text-white border border-slate-700 rounded-lg focus:outline-none focus:ring-2 focus:ring-[#EA580C]"
                />
              </div>
            )}

            {requires2FA && (
              <div>
                <label className="block text-sm font-medium text-slate-300 mb-1">
                  6-Digit Authenticator Code
                </label>
                <input
                  type="text"
                  inputMode="numeric"
                  pattern="[0-9]{6}"
                  maxLength={6}
                  required
                  autoFocus
                  value={totpCode}
                  onChange={(e) => setTotpCode(e.target.value.replace(/\D/g, '').slice(0, 6))}
                  placeholder="000000"
                  className="w-full min-h-[48px] px-4 py-2 text-lg font-mono tracking-[0.35em] text-center bg-slate-950 text-white border border-slate-700 rounded-lg focus:outline-none focus:ring-2 focus:ring-[#EA580C]"
                />
              </div>
            )}

            {needsSetup && requiresSetupKey && (
              <div>
                <label className="block text-sm font-medium text-slate-300 mb-1">
                  Server Setup Key
                </label>
                <input
                  type="password"
                  required
                  value={setupKey}
                  onChange={(e) => setSetupKey(e.target.value)}
                  placeholder="Configured ADMIN_SETUP_KEY"
                  className="w-full min-h-[44px] px-3.5 py-2 text-sm bg-slate-950 text-white border border-slate-700 rounded-lg focus:outline-none focus:ring-2 focus:ring-[#EA580C]"
                />
              </div>
            )}

            <button
              type="submit"
              disabled={submitting}
              className="w-full min-h-[46px] px-4 py-2.5 text-sm font-semibold text-white bg-[#EA580C] rounded-lg hover:bg-orange-600 disabled:opacity-60 transition-colors"
            >
              {submitting
                ? 'Please wait...'
                : needsSetup
                  ? 'Create Super Admin & Continue'
                  : requires2FA
                    ? 'Verify 2FA & Sign In'
                    : 'Sign In to Admin Portal'}
            </button>

            {requires2FA && (
              <button
                type="button"
                onClick={() => {
                  setRequires2FA(false);
                  setTotpCode('');
                  setInfoMsg(null);
                  setError(null);
                }}
                className="w-full text-xs text-slate-400 hover:text-slate-200 underline"
              >
                Use a different account or re-enter password
              </button>
            )}
          </form>
        )}
      </div>
    </div>
  );
}
